/**
 * Attaches already-uploaded files to a tenancy of the landlord's: move-in photos (up to 10 per
 * tenancy, S-04), agreement or ID proof. The tenancy is read through RLS, so another landlord's
 * tenancy id is Not found.
 */
export async function attachDocuments(
  db: SupabaseClient,
  admin: SupabaseClient,
  landlordId: string,
  input: { tenancyId: string; type: TenancyDocumentType; files: Omit<FinishedFile, "type">[] },
): Promise<Result<{ count: number }>> {
  if (!isUuid(input.tenancyId)) return { ok: false, error: NOT_FOUND };
  if (!["move_in_photo", "agreement", "id_proof"].includes(input.type) || input.files.length === 0) {
    return { ok: false, error: SAVE_FAILED };
  }
  const { data: tenancy } = await db.from("tenancy").select("id, unit_id").eq("id", input.tenancyId).maybeSingle();
  if (!tenancy) return { ok: false, error: NOT_FOUND };
  const t = tenancy as { id: string; unit_id: string };

  if (input.type === "move_in_photo") {
    const { count } = await db
      .from("document")
      .select("id", { count: "exact", head: true })
      .eq("tenancy_id", t.id)
      .eq("type", "move_in_photo");
    if ((count ?? 0) + input.files.length > 10) return { ok: false, error: "A tenancy keeps at most 10 move-in photos." };
  }

  const verified = await verifyUploads(
    db,
    admin,
    landlordId,
    input.files.map((f) => ({ ...f, type: input.type })),
  );
  if (!verified.ok) return { ok: false, error: verified.error };
  const { error } = await db
    .from("document")
    .insert(verified.files.map((f) => ({ ...f, landlord_id: landlordId, unit_id: t.unit_id, tenancy_id: t.id, uploaded_by: "landlord" })));
  if (error) return { ok: false, error: SAVE_FAILED };
  return { ok: true, count: verified.files.length };
}

