/**
 * D-05: End tenancy sets `ended_on` and `status = ended`. From that moment the tenant link is
 * revoked (E4-2: the tenant server accepts `tenant_token` only while status is active), no more
 * rent rows are created, and the unit shows Vacant. Writes an audit event (D-14).
 */
export async function endTenancy(
  db: SupabaseClient,
  landlordId: string,
  tenancyId: string,
  endedOn: string,
  today: IsoDate,
): Promise<Result<object, "endedOn">> {
  if (!isUuid(tenancyId)) return { ok: false, error: NOT_FOUND };
  if (!isIsoDate(endedOn)) return { ok: false, error: "Choose the move-out date.", fieldErrors: { endedOn: "Choose the move-out date." } };
  const { data: tenancy } = await db.from("tenancy").select("id, status, moved_in_on").eq("id", tenancyId).maybeSingle();
  if (!tenancy) return { ok: false, error: NOT_FOUND };
  const t = tenancy as { id: string; status: string; moved_in_on: IsoDate };
  if (t.status !== "active") return { ok: false, error: "This tenancy has already ended." };
  if (endedOn < t.moved_in_on) {
    const message = "The move-out date cannot be before the move-in date.";
    return { ok: false, error: message, fieldErrors: { endedOn: message } };
  }
  if (endedOn > today) {
    const message = "The move-out date cannot be in the future. End the tenancy on the day they leave.";
    return { ok: false, error: message, fieldErrors: { endedOn: message } };
  }
  const { data, error } = await db
    .from("tenancy")
    .update({ status: "ended", ended_on: endedOn })
    .eq("id", tenancyId)
    .eq("status", "active")
    .select("id");
  if (error) return { ok: false, error: SAVE_FAILED };
  if (!data || data.length === 0) return { ok: false, error: "This tenancy has already ended." };
  await audit(db, {
    landlord_id: landlordId,
    entity_type: "tenancy",
    entity_id: tenancyId,
    kind: "tenancy_ended",
    old_value: { status: "active" },
    new_value: { status: "ended", ended_on: endedOn },
  });
  return { ok: true };
}

export async function recordNotice(
  db: SupabaseClient,
  landlordId: string,
  tenancyId: string,
  givenOn: string,
  vacateOn: string,
): Promise<Result<object, "givenOn" | "vacateOn">> {
  if (!isUuid(tenancyId)) return { ok: false, error: NOT_FOUND };
  const fieldErrors: FieldErrors<"givenOn" | "vacateOn"> = {};
  if (!isIsoDate(givenOn)) fieldErrors.givenOn = "Choose the date notice was given.";
  if (!isIsoDate(vacateOn)) fieldErrors.vacateOn = "Choose the date they will vacate.";
  else if (isIsoDate(givenOn) && vacateOn < givenOn) fieldErrors.vacateOn = "The vacate date cannot be before the notice date.";
  if (hasErrors(fieldErrors)) return { ok: false, error: "Check the highlighted fields.", fieldErrors };

  const { data: tenancy } = await db
    .from("tenancy")
    .select("id, status, notice_given_on, notice_vacate_on")
    .eq("id", tenancyId)
    .maybeSingle();
  if (!tenancy) return { ok: false, error: NOT_FOUND };
  const t = tenancy as { id: string; status: string; notice_given_on: IsoDate | null; notice_vacate_on: IsoDate | null };
  if (t.status !== "active") return { ok: false, error: "Notice can only be recorded for a current tenancy." };

  const { error } = await db
    .from("tenancy")
    .update({ notice_given_on: givenOn, notice_vacate_on: vacateOn })
    .eq("id", tenancyId)
    .eq("status", "active");
  if (error) return { ok: false, error: SAVE_FAILED };
  await audit(db, {
    landlord_id: landlordId,
    entity_type: "tenancy",
    entity_id: tenancyId,
    kind: "notice_recorded",
    old_value: { notice_given_on: t.notice_given_on, notice_vacate_on: t.notice_vacate_on },
    new_value: { notice_given_on: givenOn, notice_vacate_on: vacateOn },
  });
  return { ok: true };
}
