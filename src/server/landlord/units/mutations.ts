/**
 * Creates the unit, and its property first when the landlord chose "Add a property…" (D-39).
 * The unit's `door_token` is generated by the database default on insert (D-01).
 */
export async function createUnit(db: SupabaseClient, landlordId: string, input: NewUnitInput): Promise<Result<{ unitId: string }, UnitField>> {
  const [{ data: properties, error: pError }, { data: units, error: uError }] = await Promise.all([
    db.from("property").select("id, name"),
    db.from("unit").select("id, property_id, unit_number"),
  ]);
  if (pError || uError) return { ok: false, error: SAVE_FAILED };
  const propertyNames = new Map((properties as { id: string; name: string }[]).map((p) => [p.id, p.name]));
  const existing = (units as { id: string; property_id: string; unit_number: string }[]).map((u) => ({
    id: u.id,
    propertyId: u.property_id,
    unitNumber: u.unit_number,
  }));
  const fieldErrors = validateNewUnit(input, existing, propertyNames);
  if (hasErrors(fieldErrors)) return { ok: false, error: "Check the highlighted fields.", fieldErrors };

  let propertyId = input.propertyId;
  let createdProperty: string | null = null;
  if (propertyId === null) {
    const { data, error } = await db
      .from("property")
      // `property` has no landlord_id default or derive trigger; RLS checks it is the caller's.
      .insert({ landlord_id: landlordId, name: input.propertyName.trim(), address: input.propertyAddress.trim() })
      .select("id")
      .single();
    if (error || !data) return { ok: false, error: SAVE_FAILED };
    propertyId = (data as { id: string }).id;
    createdProperty = propertyId;
  }

  const { data, error } = await db
    .from("unit")
    .insert({
      property_id: propertyId,
      unit_number: input.unitNumber.trim(),
      type: input.type.trim() || null,
      rent: input.rent,
      deposit_amount: input.deposit ?? 0,
    })
    .select("id")
    .single();
  if (error || !data) {
    if (createdProperty) await db.from("property").delete().eq("id", createdProperty);
    if (error?.code === UNIQUE_VIOLATION) {
      const name = propertyNames.get(propertyId) ?? input.propertyName.trim();
      return { ok: false, error: "Check the highlighted fields.", fieldErrors: { unitNumber: duplicateUnitMessage(input.unitNumber, name) } };
    }
    return { ok: false, error: SAVE_FAILED };
  }
  return { ok: true, unitId: (data as { id: string }).id };
}

