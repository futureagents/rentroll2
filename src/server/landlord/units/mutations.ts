export interface AddTenancyInput extends TenancyFields {
  /** Move-in condition photos already uploaded through `startUpload` (may be empty: the step is skippable). */
  photos: FinishedFile[];
  idProof: FinishedFile | null;
}

/**
 * Saving creates the tenancy (its `tenant_token` comes from the database default, D-01), its first
 * agreement (D-08), its first rent row (D-24) and its documents (D-15). Only while the unit has no
 * active tenancy (D-39; the database's one-active-per-unit index enforces it too). Anything that
 * fails after the tenancy row is written deletes the tenancy, which cascades the rest.
 */
export async function addTenancy(
  db: SupabaseClient,
  admin: SupabaseClient,
  landlordId: string,
  unitId: string,
  input: AddTenancyInput,
): Promise<Result<{ tenancyId: string }, TenancyField>> {
  if (!isUuid(unitId)) return { ok: false, error: NOT_FOUND };
  const fieldErrors = validateTenancy(input);
  if (hasErrors(fieldErrors)) return { ok: false, error: "Check the highlighted fields.", fieldErrors };

  const photos = input.photos.map((p) => ({ ...p, type: "move_in_photo" as const }));
  const idProof = input.idProof ? [{ ...input.idProof, type: "id_proof" as const }] : [];
  if (photos.length > 10) return { ok: false, error: "Add at most 10 photos." };

  const { data: unit } = await db.from("unit").select("id").eq("id", unitId).maybeSingle();
  if (!unit) return { ok: false, error: NOT_FOUND };
  const { count: active } = await db
    .from("tenancy")
    .select("id", { count: "exact", head: true })
    .eq("unit_id", unitId)
    .eq("status", "active");
  if ((active ?? 0) > 0) return { ok: false, error: "This unit already has a tenant. End that tenancy first." };

  const verified = await verifyUploads(db, admin, landlordId, [...photos, ...idProof]);
  if (!verified.ok) return { ok: false, error: verified.error };

  const { data: created, error: tenancyError } = await db
    .from("tenancy")
    .insert({
      unit_id: unitId,
      name: input.name.trim(),
      phone: storedPhone(input.phone),
      email: input.email.trim() || null,
      moved_in_on: input.movedInOn,
      deposit_paid: input.depositPaid,
      deposit_received_on: input.depositReceivedOn || null,
    })
    .select("id")
    .single();
  if (tenancyError || !created) {
    if (tenancyError?.code === UNIQUE_VIOLATION) return { ok: false, error: "This unit already has a tenant. End that tenancy first." };
    return { ok: false, error: SAVE_FAILED };
  }
  const tenancyId = (created as { id: string }).id;
  const undo = async () => {
    await db.from("tenancy").delete().eq("id", tenancyId);
  };

  const { data: agreement, error: agreementError } = await db
    .from("agreement")
    .insert({
      tenancy_id: tenancyId,
      starts_on: input.startsOn,
      ends_on: input.endsOn,
      rent: input.rent,
      rent_due_day: input.rentDueDay,
    })
    .select("id")
    .single();
  if (agreementError || !agreement) {
    await undo();
    return { ok: false, error: SAVE_FAILED };
  }

  const row = firstRentRow(input.movedInOn as IsoDate, { rent: input.rent as number, rentDueDay: input.rentDueDay as number });
  const { error: rentError } = await db
    .from("rent_entry")
    .upsert(
      { ...row, tenancy_id: tenancyId, unit_id: unitId, agreement_id: (agreement as { id: string }).id },
      { onConflict: "tenancy_id,month", ignoreDuplicates: true },
    );
  if (rentError) {
    await undo();
    return { ok: false, error: SAVE_FAILED };
  }

  if (verified.files.length > 0) {
    const { error: documentError } = await db
      .from("document")
      .insert(verified.files.map((f) => ({ ...f, landlord_id: landlordId, unit_id: unitId, tenancy_id: tenancyId, uploaded_by: "landlord" })));
    if (documentError) {
      await undo();
      return { ok: false, error: SAVE_FAILED };
    }
  }
  return { ok: true, tenancyId };
}

