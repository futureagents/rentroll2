export async function updateUnit(db: SupabaseClient, unitId: string, input: UnitFields): Promise<Result<object, keyof UnitFields>> {
  if (!isUuid(unitId)) return { ok: false, error: NOT_FOUND };
  const { data: unit } = await db.from("unit").select("id, property_id, unit_number").eq("id", unitId).maybeSingle();
  if (!unit) return { ok: false, error: NOT_FOUND };
  const u = unit as { id: string; property_id: string; unit_number: string };
  const [{ data: siblings }, { data: property }] = await Promise.all([
    db.from("unit").select("id, property_id, unit_number").eq("property_id", u.property_id),
    db.from("property").select("name").eq("id", u.property_id).single(),
  ]);
  const fieldErrors = validateUnitEdit(
    { id: u.id, propertyId: u.property_id, unitNumber: u.unit_number },
    input,
    ((siblings ?? []) as { id: string; property_id: string; unit_number: string }[]).map((s) => ({
      id: s.id,
      propertyId: s.property_id,
      unitNumber: s.unit_number,
    })),
    (property as { name: string } | null)?.name ?? "This property",
  );
  if (hasErrors(fieldErrors)) return { ok: false, error: "Check the highlighted fields.", fieldErrors };

  const { error } = await db
    .from("unit")
    .update({ unit_number: input.unitNumber.trim(), type: input.type.trim() || null, rent: input.rent, deposit_amount: input.deposit ?? 0 })
    .eq("id", unitId);
  if (error?.code === UNIQUE_VIOLATION) {
    return {
      ok: false,
      error: "Check the highlighted fields.",
      fieldErrors: { unitNumber: duplicateUnitMessage(input.unitNumber, (property as { name: string } | null)?.name ?? "This property") },
    };
  }
  return error ? { ok: false, error: SAVE_FAILED } : { ok: true };
}

export const DELETE_BLOCKED = "Only a unit that has never had a tenant or a repair can be deleted.";

/**
 * D-39: "delete is allowed only for a unit with no tenancy history". Repair history blocks it as
 * well: deleting the unit would cascade away request costs that L-09 and L-14 report.
 */
export async function deleteUnit(db: SupabaseClient, admin: SupabaseClient, unitId: string): Promise<Result> {
  if (!isUuid(unitId)) return { ok: false, error: NOT_FOUND };
  const { data: unit } = await db.from("unit").select("id").eq("id", unitId).maybeSingle();
  if (!unit) return { ok: false, error: NOT_FOUND };
  const [{ count: tenancies }, { count: requests }, { data: documents }] = await Promise.all([
    db.from("tenancy").select("id", { count: "exact", head: true }).eq("unit_id", unitId),
    db.from("request").select("id", { count: "exact", head: true }).eq("unit_id", unitId),
    db.from("document").select("storage_path").eq("unit_id", unitId),
  ]);
  if ((tenancies ?? 0) > 0 || (requests ?? 0) > 0) return { ok: false, error: DELETE_BLOCKED };
  const { error } = await db.from("unit").delete().eq("id", unitId);
  if (error) return { ok: false, error: SAVE_FAILED };
  await removeObjects(admin, ((documents ?? []) as { storage_path: string }[]).map((d) => d.storage_path));
  return { ok: true };
}

/** 20 random bytes as 40 hex characters, the same shape as `app.new_token()` (D-01: ≥128 bits). */
export function newToken(): string {
  return randomBytes(20).toString("hex");
}

/**
 * D-01: the door code can be replaced by the landlord, which is the only way to revoke it; the
 * printed stickers stop working. Writes an audit event (D-14). The token itself is never logged.
 */
export async function regenerateDoorToken(db: SupabaseClient, landlordId: string, unitId: string): Promise<Result> {
  if (!isUuid(unitId)) return { ok: false, error: NOT_FOUND };
  const { data, error } = await db.from("unit").update({ door_token: newToken() }).eq("id", unitId).select("id");
  if (error) return { ok: false, error: SAVE_FAILED };
  if (!data || data.length === 0) return { ok: false, error: NOT_FOUND };
  await audit(db, { landlord_id: landlordId, entity_type: "unit", entity_id: unitId, kind: "door_token_regenerated" });
  return { ok: true };
}

