// Writes for L-08, L-09 and L-11 (D-01, D-05, D-13, D-14, D-15, D-24, D-39). `db` is always the
// landlord's own RLS-scoped client, so another landlord's rows are absent (E4-5) and every insert
// is checked against `landlord_id = app.current_landlord_id()`. `admin` (service role) is passed
// only where storage is touched, and only for the landlord's own folder (./files.ts).
//
// Supabase's REST API has no multi-statement transaction. A save that writes several rows undoes
// what it wrote if a later row fails; the proper fix is one database function per action
// (listed under Integration requirements in the lane PR, since migrations are not this lane's).

export type Result<T = object, F extends string = string> =
  | ({ ok: true } & T)
  | { ok: false; error: string; fieldErrors?: FieldErrors<F> };

const NOT_FOUND = "Not found.";
/** E1-07. */
const SAVE_FAILED = "Could not save. Your changes are still here — try again.";

/** Postgres unique_violation. */
const UNIQUE_VIOLATION = "23505";

async function audit(
  db: SupabaseClient,
  row: { landlord_id: string; entity_type: string; entity_id: string; kind: string; old_value?: unknown; new_value?: unknown },
) {
  const { error } = await db.from("audit_event").insert({ actor: "landlord", ...row });
  return error;
}

